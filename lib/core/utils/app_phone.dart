/// بوابة واحدة لأي رقم موبايل رايح للـAPI.
///
/// ## المشكلة اللي البوابة دي موجودة عشانها
///
/// الـcubits كانت بتلزق كود الدولة على الرقم **وهو لسه فيه الصفر**:
///
/// ```dart
/// '+20' + '01113000000'   // ← '+2001113000000'  صفر زيادة
/// ```
///
/// والباك-إند بيقبل **الصيغة المحلية بالصفر بس** — اتأكدنا منها بالتجربة
/// على `POST /api/user/auth/login`:
///
/// | المبعوت            | الرد               |
/// |--------------------|--------------------|
/// | `01113000000`      | `success: true`    |
/// | `+201113000000`    | `invalid_credentials` |
/// | `201113000000`     | `invalid_credentials` |
/// | `+2001113000000`   | `invalid_credentials` |
///
/// يعني الباك-إند **مابينرملش** الأرقام، والأبلكيشن كان بيبعت صيغة رابعة
/// مالهاش وجود. الدخول والتسجيل كانوا بيقعوا الاتنين، والباج كان مستخبي
/// طول ما الأبلكيشن شغال على mock.
///
/// ⚠ **السوق مصر بس.** [toApiFormat] بيرجّع الصيغة المصرية المحلية
/// (`01xxxxxxxxx`) ومابيحترمش كود دولة تاني. لو اتفتح سوق تاني، ده أول
/// مكان لازم يتغيّر — و`AppRegex.isPhoneNumberValid` معاه.
class AppPhone {
  const AppPhone._();

  /// بيحوّل أي صيغة كتبها المستخدم للصيغة المحلية اللي الـAPI بيقبلها.
  ///
  /// ```dart
  /// AppPhone.toApiFormat('01113000000')     // '01113000000'
  /// AppPhone.toApiFormat('+201113000000')   // '01113000000'
  /// AppPhone.toApiFormat('+2001113000000')  // '01113000000'  ← اللي كان بيتبعت
  /// AppPhone.toApiFormat('1113000000')      // '01113000000'
  /// AppPhone.toApiFormat('011 130 00000')   // '01113000000'
  /// ```
  static String toApiFormat(String raw) {
    // أي حاجة مش رقم بتطير: `+` والمسافات والشرط والأقواس.
    var digits = raw.replaceAll(RegExp(r'\D'), '');

    // كود مصر بيتشال بصيغتيه. الترتيب مهم — `0020` بيتشاف قبل `20`
    // عشان ما يتقصّش غلط.
    if (digits.startsWith('0020')) {
      digits = digits.substring(4);
    } else if (digits.startsWith('20')) {
      // موبايل مصري عمره ما بيبدأ بـ`20` (بيبدأ 010/011/012/015)،
      // فالبادئة دي كود دولة أكيد مش جزء من الرقم.
      digits = digits.substring(2);
    }

    // الصفر بيترجّع لو المستخدم كتب الرقم من غيره.
    if (digits.isNotEmpty && !digits.startsWith('0')) {
      digits = '0$digits';
    }

    return digits;
  }
}
